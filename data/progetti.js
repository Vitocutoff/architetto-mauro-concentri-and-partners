// Helpers per le pagine slug
export function findProjectBySlug(slug) {
  if (!slug) return null;

  for (const category of progettiCategories) {
    const project = category.projects?.find((p) => p.slug === slug);
    if (project) return { category, project };
  }

  return null;
}
